CREATE TABLE email_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    purpose VARCHAR(30) NOT NULL,
    code_hash VARCHAR(64) NOT NULL,
    code_expires_at TIMESTAMP NOT NULL,
    verification_attempts INTEGER NOT NULL,
    code_consumed_at TIMESTAMP,
    request_count INTEGER NOT NULL,
    request_window_started_at TIMESTAMP NOT NULL,
    last_sent_at TIMESTAMP NOT NULL,
    verification_token_hash VARCHAR(64),
    token_expires_at TIMESTAMP,
    token_consumed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT ck_email_verifications_purpose
        CHECK (purpose IN ('SIGN_UP', 'FIND_ID', 'PASSWORD_RESET')),
    CONSTRAINT ck_email_verifications_code_hash_length
        CHECK (CHAR_LENGTH(code_hash) = 64),
    CONSTRAINT ck_email_verifications_attempts
        CHECK (verification_attempts >= 0),
    CONSTRAINT ck_email_verifications_request_count
        CHECK (request_count >= 1),
    CONSTRAINT ck_email_verifications_token_hash_length
        CHECK (
            verification_token_hash IS NULL
            OR CHAR_LENGTH(verification_token_hash) = 64
        ),
    CONSTRAINT ck_email_verifications_token_fields
        CHECK (
            (
                verification_token_hash IS NULL
                AND token_expires_at IS NULL
                AND token_consumed_at IS NULL
            )
            OR
            (
                verification_token_hash IS NOT NULL
                AND token_expires_at IS NOT NULL
            )
        ),
    CONSTRAINT uk_email_verifications_email_purpose
        UNIQUE (email, purpose),
    CONSTRAINT uk_email_verifications_token_hash
        UNIQUE (verification_token_hash)
);
