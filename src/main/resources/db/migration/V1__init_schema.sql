CREATE TABLE members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id VARCHAR(50),
    password VARCHAR(255),
    email VARCHAR(255),
    provider VARCHAR(20) NOT NULL, -- LOCAL, GOOGLE
    provider_id VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT uk_members_email UNIQUE (email) ,
    CONSTRAINT uk_members_login_id UNIQUE (login_id)
);

CREATE TABLE profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    member_id BIGINT NOT NULL ,
    nickname VARCHAR(50) NOT NULL,
    profile_image_url VARCHAR(500),
    CONSTRAINT uk_profiles_member_id UNIQUE (member_id) ,
    CONSTRAINT fk_profiles_member FOREIGN KEY (member_id) REFERENCES members (id)
);

CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    name VARCHAR(50) NOT NULL ,
    created_at TIMESTAMP NOT NULL ,
    CONSTRAINT uk_tags_name UNIQUE (name)
);

CREATE TABLE watching_rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    host_member_id BIGINT NOT NULL,
    title VARCHAR(100) NOT NULL ,
    video_url VARCHAR(500) NOT NULL ,
    video_duration_seconds INTEGER NOT NULL ,
    video_thumbnail_url VARCHAR(500) ,
    video_title VARCHAR(200) NOT NULL ,
    max_participants INTEGER NOT NULL ,
    is_public BOOLEAN NOT NULL ,
    private_code VARCHAR(50) ,
    status VARCHAR(50) NOT NULL ,
    start_at TIMESTAMP NOT NULL ,
    ended_at TIMESTAMP ,
    created_at TIMESTAMP NOT NULL ,
    updated_at TIMESTAMP ,
    CONSTRAINT uk_watching_rooms_private_code UNIQUE (private_code),
    CONSTRAINT fk_watching_rooms_host FOREIGN KEY (host_member_id) REFERENCES members (id)
);

CREATE TABLE room_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    member_id BIGINT NOT NULL ,
    room_id BIGINT NOT NULL ,
    created_at TIMESTAMP NOT NULL ,
    CONSTRAINT fk_room_participants_member FOREIGN KEY (member_id) REFERENCES members (id) ,
    CONSTRAINT fk_room_participants_room FOREIGN KEY (room_id) REFERENCES watching_rooms (id)
);

CREATE TABLE watching_room_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    room_id BIGINT  NOT NULL ,
    tag_id BIGINT NOT NULL ,
    created_at TIMESTAMP NOT NULL ,
    CONSTRAINT fk_watching_room_tags_room FOREIGN KEY (room_id) REFERENCES watching_rooms (id) ,
    CONSTRAINT fk_watching_room_tags_tag FOREIGN KEY (tag_id) REFERENCES tags (id)
);

CREATE TABLE chats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    member_id BIGINT NOT NULL ,
    room_id BIGINT NOT NULL ,
    video_position INTEGER NOT NULL , -- 초 기준, 영상 시작 = 0
    content VARCHAR(500) NOT NULL ,
    created_at TIMESTAMP NOT NULL ,
    CONSTRAINT fk_chats_member FOREIGN KEY (member_id) REFERENCES members (id) ,
    CONSTRAINT fk_chats_room FOREIGN KEY (room_id) REFERENCES watching_rooms (id)
);

CREATE TABLE polls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    room_id BIGINT NOT NULL ,
    question VARCHAR(255) NOT NULL ,
    status VARCHAR(50) NOT NULL ,
    expires_at TIMESTAMP NOT NULL ,
    created_at TIMESTAMP NOT NULL ,
    CONSTRAINT fk_polls_room FOREIGN KEY (room_id) REFERENCES watching_rooms (id)
);

CREATE TABLE poll_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    poll_id BIGINT NOT NULL ,
    content VARCHAR(255) NOT NULL ,
    CONSTRAINT fk_poll_options_poll FOREIGN KEY (poll_id) REFERENCES polls (id)
);

CREATE TABLE poll_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    poll_id BIGINT NOT NULL ,
    member_id BIGINT NOT NULL ,
    poll_option_id BIGINT NOT NULL ,
    created_at TIMESTAMP NOT NULL ,
    CONSTRAINT fk_poll_votes_poll FOREIGN KEY (poll_id) REFERENCES polls (id) ,
    CONSTRAINT fk_poll_votes_member FOREIGN KEY (member_id) REFERENCES members (id) ,
    CONSTRAINT fk_poll_votes_option FOREIGN KEY (poll_option_id) REFERENCES poll_options (id)
);

CREATE TABLE reactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    room_id BIGINT NOT NULL ,
    member_id BIGINT NOT NULL ,
    reaction_type VARCHAR(20) NOT NULL ,
    video_position INTEGER NOT NULL ,
    created_at TIMESTAMP NOT NULL ,
    CONSTRAINT fk_reactions_room FOREIGN KEY (room_id) REFERENCES watching_rooms (id) ,
    CONSTRAINT fk_reactions_member FOREIGN KEY (member_id) REFERENCES members (id)
);

CREATE TABLE reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    room_id BIGINT NOT NULL ,
    total_participants INTEGER NOT NULL ,
    chat_count INTEGER NOT NULL ,
    top_reaction_type VARCHAR(20) ,
    created_at TIMESTAMP NOT NULL ,
    CONSTRAINT uk_reports_room_id UNIQUE (room_id),
    CONSTRAINT fk_reports_room FOREIGN KEY (room_id) REFERENCES watching_rooms (id)
);

CREATE TABLE reaction_timelines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    report_id BIGINT NOT NULL ,
    start_second INTEGER NOT NULL ,
    end_second INTEGER NOT NULL ,
    reaction_count INTEGER NOT NULL ,
    CONSTRAINT fk_reaction_timelines_report FOREIGN KEY (report_id) REFERENCES reports (id)
);

CREATE TABLE reaction_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    report_id BIGINT NOT NULL ,
    reaction_type VARCHAR(20) NOT NULL ,
    count INTEGER NOT NULL ,
    CONSTRAINT fk_reaction_stats_report FOREIGN KEY (report_id) REFERENCES reports (id)
);

CREATE TABLE popular_scenes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    report_id BIGINT NOT NULL ,
    start_second INTEGER NOT NULL ,
    end_second INTEGER NOT NULL ,
    score INTEGER NOT NULL ,
    rank INTEGER NOT NULL ,
    CONSTRAINT fk_popular_scenes_report FOREIGN KEY (report_id) REFERENCES reports (id)
);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY ,
    member_id BIGINT NOT NULL ,
    room_id BIGINT ,
    type VARCHAR(30) NOT NULL ,
    title VARCHAR(100) NOT NULL ,
    content VARCHAR(255) ,
    is_read BOOLEAN NOT NULL ,
    created_at TIMESTAMP NOT NULL ,
    CONSTRAINT fk_notifications_member FOREIGN KEY (member_id) REFERENCES members (id) ,
    CONSTRAINT fk_notifications_room FOREIGN KEY (room_id) REFERENCES watching_rooms (id)
);

